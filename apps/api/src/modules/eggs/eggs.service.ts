import {
  Injectable,
  NotFoundException,
  BadRequestException,
} from '@nestjs/common';
import { PrismaService } from '../../prisma/prisma.service';

@Injectable()
export class EggsService {
  constructor(private readonly prisma: PrismaService) {}

  async listEggs(nestId?: number) {
    const where = nestId ? { nestId } : {};

    return this.prisma.egg.findMany({
      where,
      orderBy: [{ nestId: 'asc' }, { id: 'asc' }],
      include: {
        nest: {
          select: { id: true, name: true },
        },
        _count: {
          select: {
            servers: true,
            variables: true,
          },
        },
      },
    });
  }

  async getEggById(id: number) {
    const egg = await this.prisma.egg.findUnique({
      where: { id },
      include: {
        nest: true,
        variables: {
          orderBy: { sortOrder: 'asc' },
        },
        _count: {
          select: { servers: true },
        },
      },
    });

    if (!egg) {
      throw new NotFoundException(`Egg with ID ${id} not found`);
    }

    return egg;
  }

  async importEgg(nestId: number, eggJson: any) {
    const nest = await this.prisma.nest.findUnique({
      where: { id: nestId },
    });
    if (!nest) {
      throw new NotFoundException(`Nest with ID ${nestId} not found`);
    }

    if (!eggJson.name || !eggJson.docker_images || !eggJson.startup) {
      throw new BadRequestException(
        'Invalid egg JSON: missing required fields (name, docker_images, startup)',
      );
    }

    const dockerImages =
      typeof eggJson.docker_images === 'object'
        ? eggJson.docker_images
        : { Default: String(eggJson.docker_images) };

    const features: string[] = Array.isArray(eggJson.features) ? eggJson.features : [];

    const egg = await this.prisma.egg.create({
      data: {
        nestId,
        author: eggJson.author || 'support@pterodactyl.io',
        name: eggJson.name,
        description: eggJson.description || '',
        features,
        dockerImages,
        startup: eggJson.startup,
        configFiles: eggJson.config?.files ? JSON.stringify(eggJson.config.files) : null,
        configStartup: eggJson.config?.startup ?? null,
        configStop: eggJson.config?.stop ? JSON.stringify(eggJson.config.stop) : null,
        configLogs: eggJson.config?.logs ? JSON.stringify(eggJson.config.logs) : null,
        scriptContainer: eggJson.scripts?.installation?.container || 'ghcr.io/pterodactyl/installers:alpine',
        scriptEntry: eggJson.scripts?.installation?.entrypoint || 'ash',
        scriptInstall: eggJson.scripts?.installation?.script || null,
      },
    });

    if (Array.isArray(eggJson.variables)) {
      for (const [index, v] of eggJson.variables.entries()) {
        if (!v.env_variable || !v.name) continue;
        await this.prisma.eggVariable.create({
          data: {
            eggId: egg.id,
            name: v.name,
            description: v.description || '',
            envVariable: v.env_variable,
            defaultValue: v.default_value !== undefined ? String(v.default_value) : '',
            userViewable: v.user_viewable ?? true,
            userEditable: v.user_editable ?? true,
            rules: v.rules || 'nullable|string',
            sortOrder: index,
          },
        });
      }
    }

    return this.getEggById(egg.id);
  }

  async exportEgg(id: number) {
    const egg = await this.getEggById(id);

    let parsedFiles = {};
    try {
      parsedFiles = egg.configFiles ? JSON.parse(egg.configFiles) : {};
    } catch {}

    let parsedLogs = {};
    try {
      parsedLogs = egg.configLogs ? JSON.parse(egg.configLogs) : {};
    } catch {}

    return {
      _comment: 'DO NOT EDIT THIS FILE. IT WAS EXPORTED BY OBSIDIAN PANEL.',
      meta: {
        version: 'PTDL_v2',
        update_url: null,
      },
      exported_at: new Date().toISOString(),
      name: egg.name,
      author: egg.author,
      description: egg.description,
      features: egg.features,
      docker_images: egg.dockerImages,
      file_denylist: egg.fileDenylist,
      startup: egg.startup,
      config: {
        files: parsedFiles,
        startup: egg.configStartup,
        stop: egg.configStop,
        logs: parsedLogs,
      },
      scripts: {
        installation: {
          script: egg.scriptInstall || '',
          container: egg.scriptContainer,
          entrypoint: egg.scriptEntry,
        },
      },
      variables: egg.variables.map((v) => ({
        name: v.name,
        description: v.description,
        env_variable: v.envVariable,
        default_value: v.defaultValue,
        user_viewable: v.userViewable,
        user_editable: v.userEditable,
        rules: v.rules,
      })),
    };
  }

  async updateEgg(
    id: number,
    dto: {
      name?: string;
      description?: string;
      startup?: string;
      dockerImages?: Record<string, string>;
      scriptInstall?: string;
      scriptContainer?: string;
      scriptEntry?: string;
    },
  ) {
    await this.getEggById(id);

    return this.prisma.egg.update({
      where: { id },
      data: {
        name: dto.name,
        description: dto.description,
        startup: dto.startup,
        dockerImages: dto.dockerImages,
        scriptInstall: dto.scriptInstall,
        scriptContainer: dto.scriptContainer,
        scriptEntry: dto.scriptEntry,
      },
    });
  }

  async deleteEgg(id: number) {
    const egg = await this.getEggById(id);

    if (egg._count.servers > 0) {
      throw new BadRequestException(
        `Cannot delete egg '${egg.name}'. It is currently used by ${egg._count.servers} server(s).`,
      );
    }

    await this.prisma.eggVariable.deleteMany({ where: { eggId: id } });
    await this.prisma.egg.delete({ where: { id } });
    return { success: true, message: `Egg ${egg.name} deleted` };
  }
}
